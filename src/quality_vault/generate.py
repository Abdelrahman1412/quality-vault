"""Pages the vault computes instead of people writing them: the dashboard and the code map.

Only the block between the markers is generated; text around it is kept.
`qv check` fails when a generated block is stale, so the numbers never lie.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from quality_vault.subject import Subject
    from quality_vault.vault import Vault

BEGIN = "<!-- qv:begin (generated by `qv generate`; edits here are overwritten) -->"
END = "<!-- qv:end -->"


def _pct(n: int, d: int) -> str:
    return f"{round(100 * n / d)}%" if d else "n/a"


def dashboard(v: Vault) -> str:
    lines: list[str] = []
    mark = v.watermark()
    if mark:
        lines += [
            f"**Describes:** `{str(mark.get('subject_sha', ''))[:7]}` of the app, "
            f"reviewed {mark.get('reviewed_on', '?')}. "
            "`qv sweep` lists what changed since.",
            "",
        ]

    proved_by_auto = {rid for tc in v.test_cases if tc.automated for rid in tc.rules}
    lines += [
        "## Coverage by module",
        "",
        "| Module | Rules | With an automated test | Test cases | Automated | Data values | Gaps |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    totals = Counter()
    for m in v.cfg.modules:
        rules = [r for r in v.active_rules if r.module == m.name]
        tcs = [t for t in v.test_cases if t.module == m.name]
        data = [d for d in v.data if d.module == m.name]
        row = {
            "rules": len(rules),
            "auto_rules": sum(r.id in proved_by_auto for r in rules),
            "tcs": len(tcs),
            "auto_tcs": sum(t.automated for t in tcs),
            "data": len(data),
            "gaps": sum(d.seed_state == "gap" for d in data),
        }
        totals.update(row)
        lines.append(
            f"| {m.name} | {row['rules']} | {row['auto_rules']} "
            f"({_pct(row['auto_rules'], row['rules'])}) | {row['tcs']} | "
            f"{row['auto_tcs']} ({_pct(row['auto_tcs'], row['tcs'])}) | {row['data']} | "
            f"{row['gaps']} |"
        )
    lines.append(
        f"| **all** | **{totals['rules']}** | **{totals['auto_rules']}** "
        f"({_pct(totals['auto_rules'], totals['rules'])}) | **{totals['tcs']}** | "
        f"**{totals['auto_tcs']}** ({_pct(totals['auto_tcs'], totals['tcs'])}) | "
        f"**{totals['data']}** | **{totals['gaps']}** |"
    )

    by_layer = Counter(t.layer for t in v.test_cases)
    lines += [
        "",
        "## Test cases by layer",
        "",
        "Lowest layer first. A case belongs at the lowest layer that can prove it.",
        "",
        "| Layer | Test cases | Automated |",
        "|---|---:|---:|",
    ]
    for layer in v.cfg.layers:
        auto = sum(t.automated for t in v.test_cases if t.layer == layer)
        lines.append(f"| {layer} | {by_layer[layer]} | {auto} |")

    manual_only = [r for r in v.active_rules if r.id not in proved_by_auto]
    lines += ["", "## Rules with no automated test yet", ""]
    if manual_only:
        lines += [f"- **{r.id}** ({r.module}): {r.text}" for r in manual_only]
    else:
        lines.append("None.")

    gaps = [d for d in v.data if d.seed_state == "gap"]
    lines += ["", "## Seed gaps (states the demo data does not hold yet)", ""]
    if gaps:
        lines += [f"- {d.variable} = {d.value}: {d.notes}" for d in gaps]
    else:
        lines.append("None.")

    open_ = [f for f in v.findings if f.status.startswith("open")]
    ranks = Counter(f.rank for f in open_)
    lines += [
        "",
        "## Findings register",
        "",
        f"{len(open_)} open ("
        + ", ".join(f"{r}: {ranks[r]}" for r in ("R1", "R2", "R3", "R4"))
        + f"), {len(v.findings) - len(open_)} closed. Open ones, most masking first:",
        "",
    ]
    if open_:
        lines += [f"- **{f.id}** [{f.rank}] {f.title}" for f in sorted(open_, key=lambda f: f.rank)]
    else:
        lines.append("None.")
    return "\n".join(lines)


def code_map(v: Vault, subj: Subject) -> str:
    cited: dict[str, list[str]] = defaultdict(list)
    for r in v.active_rules:
        for s in r.code:
            cited[s].append(r.id)
    lines = [
        "Where each module lives in the code, and which rules cover each symbol.",
        "Open these lines instead of searching the codebase.",
        "",
    ]
    code = subj.current
    for m in v.cfg.modules:
        lines += [f"## {m.name}", "", "| Symbol | Location | Rules |", "|---|---|---|"]
        for s in m.symbols:
            sym = code.get(s)
            loc = f"`{sym.file}:{sym.line}`" if sym else "**missing**"
            rules = ", ".join(cited.get(s, [])) or "none"
            lines.append(f"| `{s}` | {loc} | {rules} |")
        lines.append("")
    if v.cfg.ignored:
        lines += ["## Not owned by a module", "", "| Symbol | Why |", "|---|---|"]
        lines += [f"| `{k}` | {why} |" for k, why in v.cfg.ignored.items()]
        lines.append("")
    return "\n".join(lines).rstrip()


def _splice(path: Path, body: str, title: str) -> str:
    current = (
        path.read_text(encoding="utf-8") if path.exists() else f"# {title}\n\n{BEGIN}\n{END}\n"
    )
    if BEGIN not in current or END not in current:
        current = current.rstrip() + f"\n\n{BEGIN}\n{END}\n"
    head, rest = current.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{body}\n{END}{tail}"


def render_all(v: Vault, subj: Subject) -> dict[Path, str]:
    dash = v.dir / "00-Home" / "Dashboard.md"
    cmap = v.dir / "01-System-Map" / "Code-Map.md"
    return {
        dash: _splice(dash, dashboard(v), "Dashboard"),
        cmap: _splice(cmap, code_map(v, subj), "Code map"),
    }


def write_all(v: Vault, subj: Subject) -> list[Path]:
    written = []
    for path, text in render_all(v, subj).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            written.append(path)
    return written
